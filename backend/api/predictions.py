from fastapi import APIRouter
from backend.models.storage import storage
from backend.services.priority_engine import priority_engine
from backend.services.similarity_engine import similarity_engine

router = APIRouter(prefix="/api/predictions", tags=["Predictions"])

@router.get("/{subject_id}")
async def get_predictions(subject_id: str):
    questions = storage.get_questions(subject_id)
    priorities = priority_engine.calculate_topic_priorities(questions)
    repeated_groups = similarity_engine.detect_repeated_questions(questions)

    likely_types = {
        "Algorithms & Traversal": "Very High (85% probability)",
        "Numerical & Rotation Tracing": "High (75% probability)",
        "Comparison & Differences": "Medium (60% probability)",
        "Basic Definitions": "Low (35% probability)"
    }

    disclaimer = (
        "Notice: The AI Priority Score and Pattern-Based Predictions are generated by analyzing "
        "historical frequency, marks distribution, recency, and syllabus weighting across previous papers. "
        "Predictions indicate high-probability exam trends and are not guaranteed."
    )

    return {
        "subject_id": subject_id,
        "important_topics": priorities,
        "likely_question_types": likely_types,
        "frequently_repeated_concepts": repeated_groups[:5],
        "disclaimer": disclaimer
    }
